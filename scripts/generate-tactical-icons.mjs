import { readFile, writeFile } from "node:fs/promises";
import icons from "@iconify-json/game-icons/icons.json" with { type: "json" };

const selected = {
  "jet-fighter": "Delapouite",
  "stealth-bomber": "Lorc",
  "commercial-airplane": "Delapouite",
  helicopter: "Lorc",
  "delivery-drone": "Delapouite",
  "rocket-flight": "Lorc",
  "radar-dish": "Lorc",
  "missile-launcher": "Delapouite",
  "missile-pod": "Lorc",
  "control-tower": "Delapouite",
  "flag-objective": "Delapouite",
};

const missing = Object.keys(selected).filter((name) => !icons.icons[name]);
if (missing.length > 0) {
  throw new Error(`Game Icons source is missing: ${missing.join(", ")}`);
}

const bodies = Object.fromEntries(
  Object.keys(selected).map((name) => [name, icons.icons[name].body]),
);

const output = `/* This file is generated by npm run symbols:generate. Do not hand-edit. */
/* Source: Game Icons via @iconify-json/game-icons, CC BY 3.0. */
export const GAME_ICON_BODIES = ${JSON.stringify(bodies, null, 2)} as const;

export const GAME_ICON_AUTHORS = ${JSON.stringify(selected, null, 2)} as const;
`;

const target = new URL("../lib/generated/game-icons.ts", import.meta.url);
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  if (current !== output) {
    throw new Error("Generated tactical icon subset is stale. Run npm run symbols:generate.");
  }
} else {
  await writeFile(target, output);
}
