import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import process from "node:process";

import {
  buildVerificationWasm,
  optimizeVerificationWasm,
  VERIFICATION_WASM_BUILD_POLICY,
  VERIFICATION_WASM_OPTIMIZER,
} from "./lib/verification-wasm-optimizer.mjs";

const root = resolve(import.meta.dirname, "..");
const crateRoot = resolve(root, "verification-rust/generic-aam");
const manifest = resolve(crateRoot, "Cargo.toml");
const wasmPath = resolve(crateRoot, "target/wasm32-unknown-unknown/release/vector_generic_aam_verifier.wasm");
const generatedPath = resolve(root, "lib/validation/generated/generic-aam-verifier-wasm.ts");
const cargo = process.env.CARGO ?? "cargo";
const check = process.argv.includes("--check");

function collect(directory) {
  return readdirSync(directory).sort().flatMap((entry) => {
    if (entry === "target") return [];
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? collect(path) : [path];
  }).filter((path) => path.endsWith(".rs") || /Cargo\.(toml|lock)$/.test(path));
}

const sourceSha256 = collect(crateRoot).reduce((hash, path) => {
  hash.update(relative(root, path)); hash.update("\0"); hash.update(readFileSync(path)); hash.update("\0"); return hash;
}, createHash("sha256"))
  .update(VERIFICATION_WASM_BUILD_POLICY)
  .update(VERIFICATION_WASM_OPTIMIZER)
  .digest("hex");

function verify(bytes, label) {
  const exports = new Set(WebAssembly.Module.exports(new WebAssembly.Module(bytes)).map(({ name }) => name));
  for (const name of ["memory", "vector_generic_aam_abi_version", "vector_generic_aam_max_input_len", "vector_generic_aam_input_reserve", "vector_generic_aam_run_json", "vector_generic_aam_output_ptr", "vector_generic_aam_output_len"]) {
    if (!exports.has(name)) throw new Error(`${label} is missing ${name}.`);
  }
  if (bytes.length >= 500_000) throw new Error(`${label} is ${bytes.length} bytes; verification artifact limit is 500000.`);
}

const wasm = await optimizeVerificationWasm(buildVerificationWasm({ root, manifest, wasmPath, cargo }));
verify(wasm, "Fresh generic-AAM verification module");
const sha256 = createHash("sha256").update(wasm).digest("hex");
const source = `// Generated by scripts/build-generic-aam-verifier.mjs. Do not edit.\nexport const GENERIC_AAM_VERIFIER_SOURCE_SHA256 = "${sourceSha256}";\nexport const GENERIC_AAM_VERIFIER_WASM_SHA256 = "${sha256}";\nexport const GENERIC_AAM_VERIFIER_WASM_BYTES = ${wasm.length};\nexport const GENERIC_AAM_VERIFIER_WASM_BASE64 = "${wasm.toString("base64")}";\n`;

if (check) {
  if (!existsSync(generatedPath)) throw new Error("Committed generic-AAM verification WASM is missing.");
  const committed = readFileSync(generatedPath, "utf8");
  if (committed !== source) throw new Error("Committed generic-AAM verification WASM does not match its private Rust crate.");
  verify(Buffer.from(committed.match(/BASE64 = "([A-Za-z0-9+/=]+)"/)?.[1] ?? "", "base64"), "Committed generic-AAM verification module");
  process.stdout.write(`${JSON.stringify({state:"verified", sourceSha256, sha256, bytes:wasm.length})}\n`);
} else {
  mkdirSync(dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, source);
  process.stdout.write(`${JSON.stringify({state:"generated", sourceSha256, sha256, bytes:wasm.length})}\n`);
}
