import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import process from "node:process";

import {
  buildCanonicalRustWasm,
  CANONICAL_RUST_BUILDER,
  CANONICAL_RUST_PLATFORM,
} from "./lib/canonical-rust-wasm-builder.mjs";

const root = resolve(import.meta.dirname, "..");
const crateRoot = resolve(root, "verification-rust/generic-aam");
const generatedPath = resolve(root, "lib/validation/generated/generic-aam-verifier-wasm.ts");
const check = process.argv.includes("--check");
const canonicalPlatform = CANONICAL_RUST_PLATFORM;
const canonicalBuilder = CANONICAL_RUST_BUILDER;

function collect(directory) {
  return readdirSync(directory).sort().flatMap((entry) => {
    if (entry === "target") return [];
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? collect(path) : [path];
  }).filter((path) => path.endsWith(".rs") || /Cargo\.(toml|lock)$/.test(path));
}

const sourceSha256 = collect(crateRoot).reduce((hash, path) => {
  hash.update(relative(root, path)); hash.update("\0"); hash.update(readFileSync(path)); hash.update("\0"); return hash;
}, createHash("sha256")).digest("hex");

function verify(bytes, label) {
  const exports = new Set(WebAssembly.Module.exports(new WebAssembly.Module(bytes)).map(({ name }) => name));
  for (const name of ["memory", "vector_generic_aam_abi_version", "vector_generic_aam_max_input_len", "vector_generic_aam_input_reserve", "vector_generic_aam_run_json", "vector_generic_aam_output_ptr", "vector_generic_aam_output_len"]) {
    if (!exports.has(name)) throw new Error(`${label} is missing ${name}.`);
  }
  if (bytes.length >= 500_000) throw new Error(`${label} is ${bytes.length} bytes; verification artifact limit is 500000.`);
}

const wasm = buildCanonicalRustWasm({
  root,
  manifestPath: "verification-rust/generic-aam/Cargo.toml",
  outputPath: "wasm32-unknown-unknown/release/vector_generic_aam_verifier.wasm",
  temporaryPrefix: "vector-generic-aam-canonical-",
  missingDockerMessage:
    "Docker was not found on PATH. The private generic-AAM WASM requires its pinned linux/amd64 builder.",
});
verify(wasm, "Fresh generic-AAM verification module");
const sha256 = createHash("sha256").update(wasm).digest("hex");
const source = `// Generated by scripts/build-generic-aam-verifier.mjs. Do not edit.\n`
  + `export const GENERIC_AAM_VERIFIER_SOURCE_SHA256 = "${sourceSha256}";\n`
  + `export const GENERIC_AAM_VERIFIER_BUILDER = "${canonicalPlatform}:${canonicalBuilder}";\n`
  + `export const GENERIC_AAM_VERIFIER_WASM_SHA256 = "${sha256}";\n`
  + `export const GENERIC_AAM_VERIFIER_WASM_BYTES = ${wasm.length};\n`
  + `export const GENERIC_AAM_VERIFIER_WASM_BASE64 = "${wasm.toString("base64")}";\n`;

if (check) {
  if (!existsSync(generatedPath)) throw new Error("Committed generic-AAM verification WASM is missing.");
  const committed = readFileSync(generatedPath, "utf8");
  const base64 = committed.match(/BASE64 = "([A-Za-z0-9+/=]+)"/)?.[1] ?? "";
  const committedWasm = Buffer.from(base64, "base64");
  const committedSha256 = createHash("sha256").update(committedWasm).digest("hex");
  if (committed !== source) {
    throw new Error(
      "Committed generic-AAM verification WASM does not match its canonical private Rust build: "
        + JSON.stringify({
          sourceSha256,
          freshSha256: sha256,
          freshBytes: wasm.length,
          committedSha256,
          committedBytes: committedWasm.length,
          canonicalPlatform,
          canonicalBuilder,
        }),
    );
  }
  verify(committedWasm, "Committed generic-AAM verification module");
  process.stdout.write(`${JSON.stringify({
    state: "verified",
    sourceSha256,
    sha256,
    bytes: wasm.length,
    canonicalPlatform,
    canonicalBuilder,
  })}\n`);
} else {
  mkdirSync(dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, source);
  process.stdout.write(`${JSON.stringify({
    state: "generated",
    sourceSha256,
    sha256,
    bytes: wasm.length,
    canonicalPlatform,
    canonicalBuilder,
  })}\n`);
}
