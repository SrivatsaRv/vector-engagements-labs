import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import process from "node:process";
import {
  assertNoPrivateSixDofVerifierBytes,
  assertNoPrivateSixDofVerifierExports,
} from "./sixdof-production-isolation.mjs";

const root = resolve(import.meta.dirname, "..");
const manifest = resolve(root, "engine-rust/Cargo.toml");
const wasmPath = resolve(
  root,
  "engine-rust/target/wasm32-unknown-unknown/release/vector_engine.wasm",
);
const generatedPath = resolve(root, "lib/engine/generated/vector-engine-wasm.ts");
const cargo = process.env.CARGO ?? "cargo";
const check = process.argv.includes("--check");

function collectSourceFiles(directory) {
  return readdirSync(directory)
    .sort()
    .flatMap((entry) => {
      if (entry === "target") return [];
      const path = join(directory, entry);
      return statSync(path).isDirectory() ? collectSourceFiles(path) : [path];
    })
    .filter((path) => path.endsWith(".rs") || /Cargo\.(toml|lock)$/.test(path));
}

const sourceSha256 = collectSourceFiles(resolve(root, "engine-rust"))
  .reduce((hash, path) => {
    hash.update(relative(root, path));
    hash.update("\0");
    hash.update(readFileSync(path));
    hash.update("\0");
    return hash;
  }, createHash("sha256"))
  .digest("hex");

function verifyModule(bytes, label) {
  const exportNames = WebAssembly.Module.exports(new WebAssembly.Module(bytes)).map(({ name }) => name);
  const exports = new Set(exportNames);
  for (const required of [
    "memory",
    "vector_abi_version",
    "vector_input_reserve",
    "vector_max_input_len",
    "vector_output_len",
    "vector_output_ptr",
    "vector_reference_run_json",
    "vector_run_json",
  ]) {
    if (!exports.has(required)) {
      throw new Error(`${label} is missing required WASM export ${required}.`);
    }
  }
  assertNoPrivateSixDofVerifierExports(exportNames, label);
  assertNoPrivateSixDofVerifierBytes(bytes, label);
  if (bytes.length >= 500_000) {
    throw new Error(`${label} is ${bytes.length} bytes; production artifact limit is 500000.`);
  }
}

try {
  execFileSync(
    cargo,
    [
      "build",
      "--locked",
      "--release",
      "--target",
      "wasm32-unknown-unknown",
      "--manifest-path",
      manifest,
    ],
    { cwd: root, stdio: "inherit" },
  );
} catch (error) {
  if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
    throw new Error("Cargo was not found on PATH. Install Rust stable before rebuilding VECTOR WASM.");
  }
  throw error;
}

const wasm = readFileSync(wasmPath);
const sha256 = createHash("sha256").update(wasm).digest("hex");
const source = `// Generated by scripts/build-rust-engine.mjs. Do not edit by hand.\n` +
  `export const VECTOR_ENGINE_SOURCE_SHA256 = "${sourceSha256}";\n` +
  `export const VECTOR_ENGINE_WASM_SHA256 = "${sha256}";\n` +
  `export const VECTOR_ENGINE_WASM_BYTES = ${wasm.length};\n` +
  `export const VECTOR_ENGINE_WASM_BASE64 = "${wasm.toString("base64")}";\n`;

if (check) {
  if (!existsSync(generatedPath)) {
    throw new Error("The committed Rust/WASM browser module is missing. Run npm run engine:rust:build.");
  }
  const committedSource = readFileSync(generatedPath, "utf8");
  const committedSourceSha = committedSource.match(
    /VECTOR_ENGINE_SOURCE_SHA256 = "([a-f0-9]{64})"/,
  )?.[1];
  const committedSha = committedSource.match(
    /VECTOR_ENGINE_WASM_SHA256 = "([a-f0-9]{64})"/,
  )?.[1];
  const committedBytes = Number(
    committedSource.match(/VECTOR_ENGINE_WASM_BYTES = (\d+)/)?.[1],
  );
  const committedBase64 = committedSource.match(
    /VECTOR_ENGINE_WASM_BASE64 = "([A-Za-z0-9+/=]+)"/,
  )?.[1];
  if (committedSourceSha !== sourceSha256) {
    throw new Error("The committed Rust/WASM browser module does not match the current Rust source. Run npm run engine:rust:build.");
  }
  if (!committedSha || !committedBase64 || !Number.isFinite(committedBytes)) {
    throw new Error("The committed Rust/WASM browser module has incomplete integrity metadata.");
  }
  const committedWasm = Buffer.from(committedBase64, "base64");
  if (
    committedWasm.length !== committedBytes ||
    createHash("sha256").update(committedWasm).digest("hex") !== committedSha
  ) {
    throw new Error("The committed Rust/WASM browser module failed its content integrity check.");
  }
  verifyModule(committedWasm, "Committed Rust/WASM module");
  verifyModule(wasm, "Freshly compiled Rust/WASM module");
  process.stdout.write(`${JSON.stringify({ state: "verified", sourceSha256, sha256: committedSha, bytes: committedBytes })}\n`);
} else {
  mkdirSync(dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, source);
  process.stdout.write(`${JSON.stringify({ state: "generated", sha256, bytes: wasm.length })}\n`);
}
