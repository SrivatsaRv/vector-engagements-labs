import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const manifest = resolve(root, "engine-rust/Cargo.toml");
const wasmPath = resolve(
  root,
  "engine-rust/target/wasm32-unknown-unknown/release/vector_engine.wasm",
);
const generatedPath = resolve(root, "lib/engine/generated/vector-engine-wasm.ts");
const cargo = process.env.CARGO ?? "cargo";
const check = process.argv.includes("--check");

try {
  execFileSync(
    cargo,
    ["build", "--release", "--target", "wasm32-unknown-unknown", "--manifest-path", manifest],
    { cwd: root, stdio: "inherit" },
  );
} catch (error) {
  if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
    throw new Error("Cargo was not found on PATH. Install Rust stable before rebuilding VECTOR WASM.");
  }
  throw error;
}

const wasm = readFileSync(wasmPath);
const sha256 = createHash("sha256").update(wasm).digest("hex");
const source = `// Generated by scripts/build-rust-engine.mjs. Do not edit by hand.\n` +
  `export const VECTOR_ENGINE_WASM_SHA256 = "${sha256}";\n` +
  `export const VECTOR_ENGINE_WASM_BYTES = ${wasm.length};\n` +
  `export const VECTOR_ENGINE_WASM_BASE64 = "${wasm.toString("base64")}";\n`;

if (check) {
  if (!existsSync(generatedPath) || readFileSync(generatedPath, "utf8") !== source) {
    throw new Error("The committed Rust/WASM browser module is stale. Run npm run engine:rust:build.");
  }
  process.stdout.write(`${JSON.stringify({ state: "verified", sha256, bytes: wasm.length })}\n`);
} else {
  mkdirSync(dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, source);
  process.stdout.write(`${JSON.stringify({ state: "generated", sha256, bytes: wasm.length })}\n`);
}
