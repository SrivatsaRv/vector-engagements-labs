import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { TP1538_AXES, TP1538_TABLE_INVENTORY } from "./lib/tp1538-aero-corpus.mjs";

const output = resolve(import.meta.dirname, "../verification-rust/tp1538-aero/src/generated_schema.rs");
const check = process.argv.includes("--check");
const rustArray = (values) => `&[${values.map((value) => `${value}.0`).join(", ")}]`;
const axisNames = Object.keys(TP1538_AXES);
const axes = axisNames.map((name) => `    AxisSpec { name: "${name}", values: ${rustArray(TP1538_AXES[name])} },`).join("\n");
const tables = TP1538_TABLE_INVENTORY.map((table) => {
  const tableAxes = table.axes.map((axis) => `"${axis}"`).join(", ");
  return `    TableSpec { id: "${table.id}", axes: &[${tableAxes}], alpha_max_deg: ${table.alphaValidityDeg[1]}.0, cell_count: ${table.cellCount} },`;
}).join("\n");
const source = `// Generated by scripts/generate-tp1538-rust-schema.mjs. Do not edit.\n\
#[rustfmt::skip]\n\
pub(crate) struct AxisSpec { pub(crate) name: &'static str, pub(crate) values: &'static [f64] }\n\
#[rustfmt::skip]\n\
pub(crate) struct TableSpec { pub(crate) id: &'static str, pub(crate) axes: &'static [&'static str], pub(crate) alpha_max_deg: f64, pub(crate) cell_count: usize }\n\
#[rustfmt::skip]\n\
pub(crate) static AXES: &[AxisSpec] = &[\n${axes}\n];\n\
#[rustfmt::skip]\n\
pub(crate) static TABLES: &[TableSpec] = &[\n${tables}\n];\n`;

if (check) {
  if (readFileSync(output, "utf8") !== source) throw new Error("Generated TP-1538 Rust schema is stale.");
  process.stdout.write(`${JSON.stringify({ state: "verified", axes: axisNames.length, tables: TP1538_TABLE_INVENTORY.length })}\n`);
} else {
  writeFileSync(output, source);
  process.stdout.write(`${JSON.stringify({ state: "generated", axes: axisNames.length, tables: TP1538_TABLE_INVENTORY.length })}\n`);
}
