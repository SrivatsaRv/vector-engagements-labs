import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

import {
  buildVerificationWasm,
  optimizeVerificationWasm,
  VERIFICATION_WASM_BUILD_POLICY,
  VERIFICATION_WASM_OPTIMIZER,
} from "./lib/verification-wasm-optimizer.mjs";

const root = resolve(import.meta.dirname, "..");
const crateRoot = resolve(root, "verification-rust/tp1538-aero");
const manifest = resolve(crateRoot, "Cargo.toml");
const wasmPath = resolve(crateRoot, "target/wasm32-unknown-unknown/release/vector_tp1538_aero_verifier.wasm");
const generatedPath = resolve(root, "lib/validation/generated/tp1538-aero-verifier-wasm.ts");
const cargo = process.env.CARGO ?? "cargo";
const check = process.argv.includes("--check");

execFileSync(process.execPath, [resolve(root, "scripts/generate-tp1538-rust-schema.mjs"), "--check"], { cwd: root, stdio: "inherit" });

function collect(directory) {
  return readdirSync(directory).sort().flatMap((entry) => {
    if (entry === "target") return [];
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? collect(path) : [path];
  }).filter((path) => path.endsWith(".rs") || /Cargo\.(toml|lock)$/u.test(path));
}

const sourceSha256 = collect(crateRoot).reduce((hash, path) => {
  hash.update(relative(root, path));
  hash.update("\0");
  hash.update(readFileSync(path));
  hash.update("\0");
  return hash;
}, createHash("sha256"))
  .update(VERIFICATION_WASM_BUILD_POLICY)
  .update(VERIFICATION_WASM_OPTIMIZER)
  .digest("hex");

function verify(bytes, label) {
  const exports = new Set(WebAssembly.Module.exports(new WebAssembly.Module(bytes)).map(({ name }) => name));
  for (const name of ["memory", "vector_tp1538_aero_abi_version", "vector_tp1538_aero_max_input_len", "vector_tp1538_aero_input_reserve", "vector_tp1538_aero_run_json", "vector_tp1538_aero_output_ptr", "vector_tp1538_aero_output_len"]) {
    if (!exports.has(name)) throw new Error(`${label} is missing ${name}.`);
  }
  if (bytes.length >= 500_000) throw new Error(`${label} is ${bytes.length} bytes; TP-1538 verification artifact limit is 500000.`);
}

const wasm = optimizeVerificationWasm(buildVerificationWasm({ root, manifest, wasmPath, cargo }));
verify(wasm, "Fresh TP-1538 verification module");
const sha256 = createHash("sha256").update(wasm).digest("hex");
const source = `// Generated by scripts/build-tp1538-aero-verifier.mjs. Do not edit.\nexport const TP1538_AERO_VERIFIER_SOURCE_SHA256 = "${sourceSha256}";\nexport const TP1538_AERO_VERIFIER_WASM_SHA256 = "${sha256}";\nexport const TP1538_AERO_VERIFIER_WASM_BYTES = ${wasm.length};\nexport const TP1538_AERO_VERIFIER_WASM_BASE64 = "${wasm.toString("base64")}";\n`;

if (check) {
  if (!existsSync(generatedPath)) throw new Error("Committed TP-1538 verification WASM is missing.");
  const committed = readFileSync(generatedPath, "utf8");
  if (committed !== source) throw new Error("Committed TP-1538 verification WASM does not match its private Rust crate.");
  verify(Buffer.from(committed.match(/BASE64 = "([A-Za-z0-9+/=]+)"/u)?.[1] ?? "", "base64"), "Committed TP-1538 verification module");
  process.stdout.write(`${JSON.stringify({ state: "verified", sourceSha256, sha256, bytes: wasm.length })}\n`);
} else {
  mkdirSync(dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, source);
  process.stdout.write(`${JSON.stringify({ state: "generated", sourceSha256, sha256, bytes: wasm.length })}\n`);
}
